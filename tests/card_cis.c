int main(void)
{
	unsigned int attr, cor;

	test_a008 = 0x2f9; /* card present */
	LOAD(ata);
	assert(be300_card_function() == 4 && !be300_wired_card());
	LOAD(ne2000);
	assert(be300_card_function() == 6 && be300_wired_card() && !be300_wireless_card());
	assert(be300_card_io_config(&attr, &cor) && attr == 0x200 && cor == 0x41);
	LOAD(xi825);
	assert(be300_wireless_card() == 1 && !be300_wired_card());
	assert(be300_card_io_config(&attr, &cor) && attr == 0x3e0 && cor == 0x41);
	LOAD(wl54cf);
	assert(be300_wireless_card() == 2 && !be300_wired_card());
	assert(be300_card_io_config(&attr, &cor) && attr == 0x200 && cor == 0x41);
	LOAD(el3);	/* 3c589: CONFIG at 0x10000, beyond the window */
	assert(be300_card_function() == 6 && !be300_wired_card());
	assert(!be300_card_io_config(&attr, &cor));
	LOAD(hermes);
	assert(!be300_wired_card() && !be300_wireless_card());
	assert(be300_card_io_config(&attr, &cor) && attr == 0x3e0 && cor == 0x41);
	LOAD(modem);	/* serial: entry 5 decodes 3f8h */
	assert(be300_card_function() == 2 && !be300_wired_card());
	assert(be300_card_io_config(&attr, &cor) && attr == 0x420 && cor == 0x45);
	test_a008 = 0x2ff; /* empty socket */
	assert(be300_card_function() == -1 && !be300_wired_card());
	assert(!be300_card_io_config(&attr, &cor));
	puts("CIS function/MANFID classification and COR selection passed for ATA, NE2000, XI-825, WL54-CF, 3c589, Hermes, modem");
	return 0;
}
